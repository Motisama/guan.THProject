        /// <summary>
        /// 读取保持寄存器03H
        /// </summary>
        /// <param name="slaveID">从站地址</param>
        /// <param name="startAddress">起始寄存器（10进制）</param>
        /// <param name="count">寄存器长度（10进制）</param>
        /// <returns>返回寄存器数据</returns>
        /// <exception cref="Exception"></exception>
        public byte[] ReadHoldingRegister(int slaveID, int startAddress, int count)
        {
            //第一步：封装请求报文
            sendBytes = new byte[8];
            sendBytes[0] = (byte)slaveID;
            sendBytes[1] = 0x03;
            sendBytes[2] = (byte)(startAddress / 256);
            sendBytes[3] = (byte)(startAddress % 256);
            sendBytes[4] = (byte)(count / 256);
            sendBytes[5] = (byte)(count % 256);
            //封装CRC校验
            byte[] crc = Crc16(sendBytes, 6);//校验前面六位
            sendBytes[6] = crc[1];
            sendBytes[7] = crc[0];

            //第二步：发送请求报文
            try
            {
                serialPort.Write(sendBytes, 0, sendBytes.Length);//发送报文，等待延时
                Thread.Sleep(ReceiveDelay);//接收缓冲等待

                //第三步：接收应答报文
                receiveBytes = new byte[serialPort.BytesToRead];
                serialPort.Read(receiveBytes, 0, receiveBytes.Length); //获得应答报文
            }
            catch(Exception ex)
            {
                throw new Exception($"发送或接收报文出现问题：{ex.Message}");
            }

            //第四步：解析应答报文
            int DataBytesLength = 2 * count;
            if (receiveBytes.Length == 5 + 2 * count)//报文长度必须合理
            {
                if (CheckCRC(receiveBytes) && receiveBytes[1] == 0x03 && receiveBytes[2] == DataBytesLength)//进一步校验
                {
                    //截取寄存器数据
                    byte[] returnDataArray = new byte[DataBytesLength];

                    //返回截取后的报文数组（从索引3开始，去掉应答报文的地址、功能码、字节计数）
                    Array.Copy(receiveBytes, 3, returnDataArray, 0, DataBytesLength);//语法：源数组，源索引，目标数组，目标索引，复制长度
                    return returnDataArray;
                }
                else return null;
            }
            else return null;
        }
