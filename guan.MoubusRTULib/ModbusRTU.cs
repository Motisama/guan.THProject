        /// <summary>
        /// 计算Modbus CRC16，返回[低字节, 高字节]，符合RTU传输顺序
        /// </summary>
        private static byte[] Crc16(byte[] pucFrame, int usLen)
        {
            // 边界校验，防止数组越界
            if (pucFrame == null || usLen <= 0 || usLen > pucFrame.Length)
                throw new ArgumentException("CRC计算参数非法");

            byte hi = 0xFF; // CRC高字节
            byte lo = 0xFF; // CRC低字节
            ushort index;
            int i = 0;

            while (usLen-- > 0)
            {
                index = (ushort)(hi ^ pucFrame[i++]);
                hi = (byte)(lo ^ aucCRCHi[index]);
                lo = aucCRCLo[index];
            }

            // 关键修正：返回顺序改为 低字节在前，高字节在后，匹配Modbus RTU规范
            return new byte[] { lo, hi };
        }

        /// <summary>
        /// 校验报文CRC是否正确
        /// </summary>
        private bool CheckCRC(byte[] value)
        {
            if (value == null || value.Length <= 2)
                return false;

            // 直接计算前N-2字节的CRC，无需额外拷贝数组
            byte[] calcCrc = Crc16(value, value.Length - 2);

            // 报文末尾2字节：倒数第二是CRC低，最后是CRC高
            return calcCrc[1] == value[value.Length - 2]
                && calcCrc[0] == value[value.Length - 1];
        }
